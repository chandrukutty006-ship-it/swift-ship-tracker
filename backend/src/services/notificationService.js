const db = require('../db/database');
const socketService = require('./socketService');

/**
 * Creates an in-app notification and dispatches a simulated email
 */
function sendNotification({
  userId,
  shipmentId,
  title,
  message,
  type = 'STATUS_UPDATE',
  trackingId = null,
  recipientEmail = null,
  recipientName = null,
}) {
  try {
    // 1. Insert In-App Notification
    const notifResult = db.run(
      `INSERT INTO notifications (user_id, shipment_id, title, message, type, is_read, created_at)
       VALUES (?, ?, ?, ?, ?, 0, datetime('now'))`,
      [userId || null, shipmentId || null, title, message, type]
    );

    const newNotification = {
      id: notifResult.lastInsertRowid,
      user_id: userId,
      shipment_id: shipmentId,
      title,
      message,
      type,
      is_read: 0,
      created_at: new Date().toISOString(),
    };

    // 2. Broadcast via Socket.IO
    socketService.broadcastNotification(newNotification);

    // 3. Dispatch Simulated Email if email is available
    if (recipientEmail) {
      const emailHtml = generateEmailTemplate({
        recipientName: recipientName || 'Valued Partner',
        title,
        message,
        trackingId: trackingId || 'SST-UNKNOWN',
        type,
      });

      db.run(
        `INSERT INTO email_logs (to_email, to_name, subject, body_html, tracking_id, event_type, sent_at)
         VALUES (?, ?, ?, ?, ?, ?, datetime('now'))`,
        [
          recipientEmail,
          recipientName || 'Valued Partner',
          `[Swift Ship] ${title} - ${trackingId || ''}`,
          emailHtml,
          trackingId,
          type,
        ]
      );
    }

    return newNotification;
  } catch (err) {
    console.error('Error dispatching notification/email:', err);
  }
}

